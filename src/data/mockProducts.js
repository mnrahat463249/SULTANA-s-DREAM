export async function fetchProductsWithCursor({
  cursor = null,
  perPage = 4,
  category = "All Pieces",
  search = "",
  sortBy = "featured"
} = {}) {
  await new Promise((resolve) => setTimeout(resolve, 200));

  let filtered = [...ALL_PRODUCTS];

  if (category && category !== "All Pieces") {
    filtered = filtered.filter((p) => p.category.toLowerCase() === category.toLowerCase());
  }

  if (search.trim()) {
    const q = search.toLowerCase();
    filtered = filtered.filter(
      (p) => p.title.toLowerCase().includes(q) || p.description.toLowerCase().includes(q) || p.category.toLowerCase().includes(q)
    );
  }

  if (sortBy === "price_asc") {
    filtered.sort((a, b) => a.price - b.price);
  } else if (sortBy === "price_desc") {
    filtered.sort((a, b) => b.price - a.price);
  } else if (sortBy === "rating") {
    filtered.sort((a, b) => b.rating - a.rating);
  }

  let startIndex = 0;
  if (cursor) {
    try {
      const decoded = atob(cursor);
      const { lastId } = JSON.parse(decoded);
      const foundIdx = filtered.findIndex((item) => item.id === lastId);
      if (foundIdx !== -1) {
        startIndex = foundIdx + 1;
      }
    } catch {
      startIndex = 0;
    }
  }

  const pageItems = filtered.slice(startIndex, startIndex + perPage);
  const nextItem = filtered[startIndex + perPage];

  let next_cursor = null;
  if (nextItem && pageItems.length > 0) {
    const lastItemOnPage = pageItems[pageItems.length - 1];
    next_cursor = btoa(JSON.stringify({ lastId: lastItemOnPage.id, _pointsToNextItems: true }));
  }

  return {
    data: pageItems,
    per_page: perPage,
    next_cursor,
    prev_cursor: cursor ? btoa(JSON.stringify({ _pointsToPrev: true })) : null,
    total_count: filtered.length,
    has_more: !!next_cursor
  };
}
